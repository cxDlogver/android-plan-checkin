def gherkin(item):
    tags = ["@" + item["id"], "@" + item["owner"], *["@"+x for x in item["fr"]], *["@"+x for x in item["at"]]]
    if item["core"]:
        tags.append("@matrix_core")
    lines = [" ".join(tags), ("Scenario Outline: " if item["examples"] else "Scenario: ") + item["id"] + " " + item["title"],
             "  Given " + item["given"], "  When " + item["when"]]
    results = item["then"].split("；")
    lines.extend(("  Then " if i == 0 else "  And ") + value for i, value in enumerate(results))
    if item["examples"]:
        lines.extend(["", "  Examples:"] + ["    | " + " | ".join(row) + " |" for row in item["examples"]])
    return "\n".join(lines)


